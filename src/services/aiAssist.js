/**
 * Unified client-side GenAI assist service.
 *
 * Resolution order for every AI capability in the app:
 *   1. Live engine -> POST /api/ai/assist (z-ai-web-dev-sdk on the backend).
 *   2. Smart Offline Planning Engine -> instant, parameter-driven fallback
 *      from src/services/assistOffline.js so no panel is ever dead.
 *
 * Every method resolves to the SAME shape:
 *   { success, source: 'live-ai' | 'local-ai-engine', data, model?, notice? }
 * Errors never throw — the offline tier absorbs them.
 */

import {
  offlineAssistantChat,
  offlineBudgetPlan,
  offlinePlanReview,
  offlineTimelinePlan,
  offlineVendorPlan,
  offlineVendorInquiry,
} from './assistOffline.js';

export const ASSIST_ENDPOINT = '/api/ai/assist';
export const ASSIST_TIMEOUT_MS = 45000;

async function postAssist(task, payload, timeoutMs = ASSIST_TIMEOUT_MS) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(ASSIST_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({ task, payload }),
    });
    const data = await response.json().catch(() => null);
    if (!response.ok || !data?.success) {
      const err = new Error(data?.error || `AI engine responded with HTTP ${response.status}.`);
      err.status = response.status;
      throw err;
    }
    return data;
  } finally {
    clearTimeout(timeoutId);
  }
}

/**
 * Run one assist task with automatic offline fallback.
 * @param {string} task - one of the six assist task ids
 * @param {object} payload - validated client-side context for the task
 * @param {(payload: object) => object} offlineFn - matching offline generator
 */
async function runTask(task, payload, offlineFn) {
  try {
    const result = await postAssist(task, payload);
    return {
      success: true,
      source: 'live-ai',
      model: result.model || 'GLM',
      data: result.data,
    };
  } catch (err) {
    if (err.name === 'AbortError') {
      console.warn(`[aiAssist] ${task} timed out — using offline engine.`);
    } else {
      console.warn(`[aiAssist] ${task} failed (${err.message}) — using offline engine.`);
    }
    return {
      success: true,
      source: 'local-ai-engine',
      notice: 'Generated by the Smart Offline Planning Engine (live AI unavailable).',
      data: offlineFn(payload),
    };
  }
}

export const aiAssist = {
  budgetPlan(payload) {
    return runTask('budget-plan', payload, offlineBudgetPlan);
  },

  timelinePlan(payload) {
    return runTask('timeline-plan', payload, offlineTimelinePlan);
  },

  vendorPlan(payload) {
    return runTask('vendor-plan', payload, offlineVendorPlan);
  },

  vendorInquiry(payload) {
    return runTask('vendor-inquiry', payload, offlineVendorInquiry);
  },

  planReview(payload) {
    return runTask('plan-review', payload, offlinePlanReview);
  },

  assistantChat(payload) {
    return runTask('assistant-chat', payload, offlineAssistantChat);
  },
};
